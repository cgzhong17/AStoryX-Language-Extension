import {REPO_ROOT,TEMP_ROOT,RESULT_ROOT,EXTENSION_ID} from './paths';
import * as vscode from 'vscode';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import {strict as assert} from 'node:assert';

interface Api {checkProject(root?:string):Promise<number>}
export async function run(){
  const extension=vscode.extensions.getExtension<Api>(EXTENSION_ID)!;
  const workspace=vscode.workspace.workspaceFolders![0].uri.fsPath;
  const root=await fs.mkdtemp(path.join(workspace,'.test-official-project-'));
  const directory=await fs.mkdtemp(path.join(TEMP_ROOT,'.test-official-source-'));
  const resultFile=path.join(RESULT_ROOT,'official-result.json'),messages:string[]=[];
  await fs.writeFile(resultFile,JSON.stringify({passed:false,status:'running'}));
  const record=(message:string)=>{messages.push(message);console.log('ASTORYX_OFFICIAL '+message);};
  const config=vscode.workspace.getConfiguration('astoryx');
  const previousDirectory=config.inspect<string>('resources.officialConfigDirectory')?.globalValue;
  const previousEnabled=config.inspect<boolean>('resources.officialAssetsEnabled')?.globalValue;
  const previousResourceChecks=config.inspect<boolean>('validation.resourceChecks')?.globalValue;
  const previousHints=config.inspect<boolean>('inlayHints.enabled')?.globalValue;
  const collections={characterTachies:{avg_003_kalts_1:'kalts.ab',avg_4179_monstr_1:'monstr.ab',avg_uncollected_1:'raw.ab'}};
  const userConfigs={characterTachieOfficialConfigs:{avg_003_kalts_1:{name:'凯尔希',variationNames:{'#1$1':'默认','#12$1':'wink'}},avg_4179_monstr_1:{name:'mon3tr',variationNames:{'#1$1':'默认','#5$1':'疑惑','#1$2':'#1$2'}}}};
  const script=vscode.Uri.file(path.join(root,'Stories/main.astoryx'));
  try{
    const api=await extension.activate();
    await config.update('resources.officialAssetsEnabled',true,vscode.ConfigurationTarget.Global);
    await config.update('resources.officialConfigDirectory',directory,vscode.ConfigurationTarget.Global);
    const write=async(file:string,text:string)=>{const uri=vscode.Uri.file(file);await vscode.workspace.fs.createDirectory(vscode.Uri.file(path.dirname(file)));await vscode.workspace.fs.writeFile(uri,Buffer.from(text));return uri;};
    await write(path.join(root,'Rules/BaseRule.json'),await fs.readFile(path.join(REPO_ROOT,'test/fixtures/language-demo/Rules/BaseRule.json'),'utf8'));
    const collectionFile=path.join(directory,'officialAssets_collections.json');
    const userConfigFile=path.join(directory,'officialAssets_userConfigs.json');
    await write(collectionFile,JSON.stringify(collections));await write(userConfigFile,JSON.stringify(userConfigs));
    const prefix='官方资源测试\n#useRule:BaseRule\n#aliases\navg_003_kalts_1->凯尔希\navg_uncollected_1->凯尔希alts_1\n#endaliases\n';
    await write(script.fsPath,prefix+'--mon3tr:\n--mon3tr:不存在/1\n--avg_uncollected_1:#1$1/0\n--凯尔希alts_1:#1$1/1');
    const document=await vscode.workspace.openTextDocument(script);await vscode.window.showTextDocument(document);
    const wait=async(predicate:(diagnostics:vscode.Diagnostic[])=>boolean)=>{
      const deadline=Date.now()+12000;
      while(Date.now()<deadline){const diagnostics=vscode.languages.getDiagnostics(script);if(predicate(diagnostics))return diagnostics;await new Promise(r=>setTimeout(r,30));}
      throw new Error('Official diagnostics timeout: '+JSON.stringify(vscode.languages.getDiagnostics(script).map(d=>({code:d.code,line:d.range.start.line,message:d.message}))));
    };
    const replace=async(text:string)=>{const edit=new vscode.WorkspaceEdit();edit.replace(script,new vscode.Range(document.positionAt(0),document.positionAt(document.getText().length)),text);assert.ok(await vscode.workspace.applyEdit(edit));};
    const complete=async(line:number)=>{
      const list=await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider',script,new vscode.Position(line,document.lineAt(line).text.length));
      return list.items.map(i=>typeof i.label==='string'?i.label:i.label.label);
    };
    const waitComplete=async(line:number,predicate:(labels:string[])=>boolean)=>{
      const deadline=Date.now()+10000;let labels:string[]=[];
      while(Date.now()<deadline){labels=await complete(line);if(predicate(labels))return labels;await new Promise(r=>setTimeout(r,30));}
      throw new Error('Completion did not update: '+JSON.stringify(labels));
    };
    let diagnostics=await wait(ds=>ds.some(d=>d.code==='W1004')&&ds.filter(d=>d.code==='W1005').length===2);
    let labels=await complete(6);assert.ok(labels.includes('疑惑')&&labels.includes('默认')&&labels.includes('#1$2'));assert.ok(!labels.includes('#1$1'));
    const variant=diagnostics.find(d=>d.code==='W1004')!;assert.equal(document.getText(variant.range),'不存在');assert.equal(variant.severity,vscode.DiagnosticSeverity.Warning);
    record('Real completion after --mon3tr: uses variationNames values; invalid variants receive precise W1004 warnings');
    const rawWarnings=diagnostics.filter(d=>d.code==='W1005');
    assert.equal(rawWarnings[0].message,rawWarnings[1].message);assert.equal(document.getText(rawWarnings[1].range),'凯尔希alts_1');
    assert.equal(await api.checkProject(root),0);
    record('Raw IDs and their script aliases receive identical W1005 warnings without failing the project');
    await replace('名称与内联提示测试\n#useRule:BaseRule\nmon3tr\t你好\n凯尔希\t你好\n未知角色\t你好');
    diagnostics=await wait(ds=>ds.length===1&&ds[0].code==='W1001'&&ds[0].range.start.line===4);
    assert.equal(document.getText(diagnostics[0].range),'未知角色');
    await config.update('validation.resourceChecks',false,vscode.ConfigurationTarget.Global);
    await replace(document.getText()+'。');
    await wait(ds=>ds.length===1&&ds[0].code==='W1001'&&ds[0].range.start.line===4);
    await config.update('validation.resourceChecks',previousResourceChecks,vscode.ConfigurationTarget.Global);
    record('Direct userConfigs names are valid dialogue speakers even with resource checks disabled; unknown names still warn');
    const priorityPrefix='名称优先级测试\n#useRule:BaseRule\n#aliases\navg_uncollected_1->mon3tr\n凯尔希->第一层\n第一层->第二层\n#endaliases\n';
    await replace(priorityPrefix+'--mon3tr:\n--第二层:\n--mon3tr:疑惑/1\n--第二层:wink/0');
    labels=await complete(7);assert.ok(labels.includes('疑惑'));
    labels=await complete(8);assert.ok(labels.includes('wink'));
    await wait(ds=>ds.length===0);
    record('userConfigs wins over conflicting script aliases; multiple alias parents share collected variants');
    await config.update('inlayHints.enabled',true,vscode.ConfigurationTarget.Global);
    const hintPrefix='参数内联提示测试\n#useRule:BaseRule\n';
    await replace(hintPrefix+'--mon3tr:疑惑/1/true');
    const hints=async()=>await vscode.commands.executeCommand<vscode.InlayHint[]>('vscode.executeInlayHintProvider',script,new vscode.Range(0,0,document.lineCount,0));
    const label=(hint:vscode.InlayHint)=>typeof hint.label==='string'?hint.label:hint.label.map(p=>p.value).join('');
    let shown=await hints();const unchanged=document.getText(),wasDirty=document.isDirty;
    assert.deepEqual(shown.map(h=>label(h)),['SlotIndex:','IsBlocker:']);
    assert.ok(shown.every(h=>h.kind===vscode.InlayHintKind.Parameter&&h.paddingRight));
    assert.equal(document.getText(),unchanged);assert.equal(document.isDirty,wasDirty);
    assert.equal(document.lineAt(2).text.slice(shown[0].position.character),'1/true');
    const hintColors=vscode.workspace.getConfiguration('workbench').get<Record<string,string>>('colorCustomizations')!;
    assert.equal(hintColors['editorInlayHint.parameterForeground'],'#FFFFFF');
    const hintDefaults=extension.packageJSON.contributes.configurationDefaults['workbench.colorCustomizations'];
    assert.ok(!Object.keys(hintDefaults).some(key=>/background/i.test(key)));
    record('Native inlay hints exclude Character/Variant, use white parameter foreground defaults, and preserve background and source text');
    await replace(hintPrefix+'--mon3tr:疑惑//false');
    shown=await hints();assert.deepEqual(shown.map(h=>label(h)),['IsBlocker:']);
    assert.equal(document.lineAt(2).text.slice(shown[0].position.character),'false');
    await config.update('inlayHints.enabled',false,vscode.ConfigurationTarget.Global);
    assert.deepEqual(await hints(),[]);
    await config.update('inlayHints.enabled',true,vscode.ConfigurationTarget.Global);
    assert.equal((await hints()).length,1);
    record('Inlay hints update after unsaved edits, preserve omitted argument positions, and honor the enable setting');
    const ruleDocument=await vscode.workspace.openTextDocument(vscode.Uri.file(path.join(root,'Rules/BaseRule.json')));
    const originalRule=ruleDocument.getText(),ruleEdit=new vscode.WorkspaceEdit();
    ruleEdit.replace(ruleDocument.uri,new vscode.Range(ruleDocument.positionAt(0),ruleDocument.positionAt(originalRule.length)),originalRule.replaceAll('IsBlocker','TestBlocker'));
    assert.ok(await vscode.workspace.applyEdit(ruleEdit));
    assert.ok((await hints()).some(h=>label(h)==='TestBlocker:'));
    const restoreRule=new vscode.WorkspaceEdit();restoreRule.replace(ruleDocument.uri,new vscode.Range(ruleDocument.positionAt(0),ruleDocument.positionAt(ruleDocument.getText().length)),originalRule);
    assert.ok(await vscode.workspace.applyEdit(restoreRule));
    assert.ok((await hints()).some(h=>label(h)==='IsBlocker:'));
    record('Unsaved project rule changes refresh the inlay parameter names and restore correctly');
    await replace(hintPrefix+'--mo');
    const nameItems=await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider',script,new vscode.Position(2,4));
    const nameItem=nameItems.items.find(item=>item.label==='mon3tr')!;
    assert.ok(nameItem);assert.equal(nameItem.insertText,'mon3tr:');
    const nameEdit=new vscode.WorkspaceEdit();nameEdit.replace(script,nameItem.range as vscode.Range,nameItem.insertText as string);assert.ok(await vscode.workspace.applyEdit(nameEdit));
    assert.equal(document.lineAt(2).text,'--mon3tr:');
    labels=await complete(2);assert.deepEqual([...labels].sort(),['#1$2','疑惑','默认'].sort());assert.equal(new Set(labels).size,labels.length);
    const getSignature=async(line:number,character=document.lineAt(line).text.length)=>await vscode.commands.executeCommand<vscode.SignatureHelp|undefined>('vscode.executeSignatureHelpProvider',script,new vscode.Position(line,character));
    assert.ok(!(await getSignature(2))?.signatures.length);
    await replace(hintPrefix+'--avg_uncollected_1:\n--mon3tr:疑惑/1\n背景：');
    assert.ok((await getSignature(2))?.signatures[0].label.includes('Character&Variant'));
    assert.ok((await getSignature(3))?.signatures[0].label.includes('SlotIndex'));
    const bgItems=await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider',script,new vscode.Position(4,3));
    assert.ok(bgItems.items.some(item=>item.label==='无'&&item.insertText!=='无:'));
    record('Character name completion inserts one ASCII colon, collected variants have one exclusive list, and full signatures remain for uncollected names and optional parameters');
    await replace(hintPrefix+'--mon3tr：疑惑/1');
    diagnostics=await wait(ds=>ds.length===1&&ds[0].code==='W1006');
    const colonWarning=diagnostics[0];assert.equal(document.getText(colonWarning.range),'：');assert.equal(colonWarning.severity,vscode.DiagnosticSeverity.Warning);
    labels=await complete(2);
    // A mistyped colon must not suggest that the variant syntax is valid.
    const variantItems=await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider',script,new vscode.Position(2,10));
    assert.deepEqual(variantItems.items,[]);
    assert.ok(!(await getSignature(2,10))?.signatures.length);
    const afterColon=await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider',script,new vscode.Position(2,9));
    assert.deepEqual(afterColon.items,[]);
    const colonActions=await vscode.commands.executeCommand<vscode.CodeAction[]>('vscode.executeCodeActionProvider',script,colonWarning.range,vscode.CodeActionKind.QuickFix.value);
    const colonAction=colonActions.find(action=>action.title.includes('英文冒号'))!;
    assert.ok(colonAction.edit);assert.ok(await vscode.workspace.applyEdit(colonAction.edit!));await wait(ds=>ds.length===0);
    assert.equal(document.lineAt(2).text,'--mon3tr:疑惑/1');
    const fixedVariants=await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider',script,new vscode.Position(2,10));
    assert.deepEqual(fixedVariants.items.map(item=>item.label).sort(),['#1$2','疑惑','默认'].sort());
    await replace(hintPrefix+'--avg_uncollected_1：');
    assert.deepEqual((await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider',script,new vscode.Position(2,document.lineAt(2).text.length))).items,[]);
    assert.ok(!(await getSignature(2))?.signatures.length);
    record('W1006 suppresses variant completion and signatures for Chinese colons, including uncollected names; fixing the colon restores the collected variants');
    await replace(prefix+'--凯尔希:\n--mon3tr:不存在/1\n--avg_uncollected_1:#1$1/0\n--凯尔希alts_1:#1$1/1');
    labels=await complete(6);assert.ok(labels.includes('wink')&&labels.includes('默认'));
    record('A script alias resolving to a collected raw ID receives the collected character variants');
    await replace(document.getText().replace('avg_003_kalts_1->凯尔希','avg_absent_1->凯尔希'));
    diagnostics=await wait(ds=>ds.some(d=>d.code==='E2001'&&d.range.start.line===3));
    const invalid=diagnostics.find(d=>d.code==='E2001')!;assert.equal(document.getText(invalid.range),'avg_absent_1');assert.equal(invalid.severity,vscode.DiagnosticSeverity.Error);
    await replace(document.getText().replace('avg_absent_1->凯尔希','avg_003_kalts_1->凯尔希'));await wait(ds=>!ds.some(d=>d.code==='E2001'));
    record('Nonexistent raw IDs error on the #aliases declaration and clear after an unsaved fix');
    const expanded={characterTachieOfficialConfigs:{...userConfigs.characterTachieOfficialConfigs,avg_uncollected_1:{name:'已收录角色',variationNames:{'#1$1':'差分A'}}}};
    await write(userConfigFile,JSON.stringify(expanded));
    await wait(ds=>!ds.some(d=>d.code==='W1005')&&ds.some(d=>d.code==='W1004'&&d.range.start.line===9));
    await replace(prefix+'--凯尔希alts_1:\n--凯尔希alts_1:差分A/1');
    labels=await complete(6);assert.ok(labels.includes('差分A'));await wait(ds=>ds.length===0);
    record('Changing official JSON outside the workspace refreshes variants and both raw/alias warnings automatically');
    const projectConfig=await write(path.join(root,'Configs/officialAssets_userConfigs.json'),JSON.stringify({characterTachieOfficialConfigs:{avg_4179_monstr_1:{name:'项目角色',variationNames:{'#project':'项目差分'}}}}));
    await replace(prefix+'--项目角色:\n--项目角色:项目差分/1');
    labels=await waitComplete(6,list=>list.includes('项目差分')&&!list.includes('疑惑'));await wait(ds=>ds.length===0);
    record('Project userConfigs takes precedence over the global file for names and variants');
    const configDocument=await vscode.workspace.openTextDocument(projectConfig);
    const editConfig=new vscode.WorkspaceEdit();editConfig.replace(projectConfig,new vscode.Range(configDocument.positionAt(0),configDocument.positionAt(configDocument.getText().length)),configDocument.getText().replaceAll('项目差分','未保存差分'));
    await vscode.workspace.applyEdit(editConfig);
    labels=await waitComplete(6,list=>list.includes('未保存差分')&&!list.includes('项目差分'));
    await wait(ds=>ds.some(d=>d.code==='W1004'));
    record('Unsaved userConfigs changes update completion and variant diagnostics together');
    await write(collectionFile,'{');diagnostics=await wait(ds=>ds.some(d=>d.code==='E1003'));
    assert.ok(!diagnostics.some(d=>d.code==='E2001'||d.code==='W1004'||d.code==='W1005'));
    await write(collectionFile,JSON.stringify(collections));await wait(ds=>!ds.some(d=>d.code==='E1003')&&ds.some(d=>d.code==='W1004'));
    record('Invalid official JSON reports E1003 without cascaded resource/variant warnings and recovers after repair');
  }catch(error){await fs.writeFile(resultFile,JSON.stringify({passed:false,messages,error:String(error),stack:(error as Error).stack},null,2));throw error;}
  finally{
    await config.update('resources.officialConfigDirectory',previousDirectory,vscode.ConfigurationTarget.Global);
    await config.update('resources.officialAssetsEnabled',previousEnabled,vscode.ConfigurationTarget.Global);
    await config.update('validation.resourceChecks',previousResourceChecks,vscode.ConfigurationTarget.Global);
    await config.update('inlayHints.enabled',previousHints,vscode.ConfigurationTarget.Global);
    for(const document of vscode.workspace.textDocuments.filter(d=>!d.isClosed&&d.uri.fsPath.startsWith(root+path.sep))){await vscode.window.showTextDocument(document);await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor');}
    assert.ok(path.resolve(root).startsWith(path.resolve(workspace)+path.sep+'.test-official-project-'));
    assert.ok(path.resolve(directory).startsWith(path.resolve(TEMP_ROOT)+path.sep+'.test-official-source-'));
    await fs.rm(root,{recursive:true,force:true,maxRetries:10,retryDelay:100});await fs.rm(directory,{recursive:true,force:true,maxRetries:10,retryDelay:100});
  }
  await fs.writeFile(resultFile,JSON.stringify({passed:true,messages},null,2));
}
